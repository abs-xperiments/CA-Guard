INVITE = "firm-invite-code"
PASS = "a-long-enough-passphrase"


@pytest.fixture(scope="module")
def csv_bytes() -> bytes:
    buffer = io.StringIO()
    generate(GeneratorConfig(seed=808, n_vouchers=400)).lines.to_csv(buffer, index=False)
    return buffer.getvalue().encode()


@pytest.fixture(autouse=True)
def _invite(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("CAGUARD_INVITE_CODE", INVITE)
    monkeypatch.delenv("CAGUARD_DEMO", raising=False)


def _client(store: Path, email: str) -> TestClient:
    client = TestClient(create_app(store))
    body = {"email": email, "name": email.split("@")[0], "password": PASS, "invite_code": INVITE}
    if client.post("/api/auth/signup", json=body).status_code != 200:
        assert client.post("/api/auth/login", json={"email": email, "password": PASS}).is_success
    return client


def _upload(client: TestClient, payload: bytes, name: str = "books.csv") -> dict:
    response = client.post("/api/engagements", files={"file": (name, payload, "text/csv")})
    assert response.status_code == 200, response.text
    return response.json()


