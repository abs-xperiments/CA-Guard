# --- the report -------------------------------------------------------------------------


def test_the_report_separates_observation_from_decision_and_documents_selection(
    tmp_path: Path, csv_bytes: bytes
) -> None:
    client = _client(tmp_path / "review.db", "partner@firm.in")
    queue = _upload(client, csv_bytes)
    engagement = queue["engagement"]["id"]
    first, second, third = (f["voucher_id"] for f in queue["findings"][:3])
    client.post(
        f"/api/engagements/{engagement}/decisions", json={"voucher_id": first, "action": "accept"}
    )
    client.post(
        f"/api/engagements/{engagement}/decisions",
        json={"voucher_id": second, "action": "reject", "note": "invoice seen and agreed"},
    )
    client.post(
        f"/api/engagements/{engagement}/decisions",
        json={"voucher_id": third, "action": "investigate"},
    )

    report = client.get(f"/api/engagements/{engagement}/report.html").text

    assert "What CA-Guard observed" in report
    assert "What the reviewer decided" in report
    assert "How these items were selected" in report and "SA 530" in report
    assert "Exception — follow up" in report and "Cleared — not a concern" in report
    (source,) = client.get(f"/api/engagements/{engagement}/sources").json()
    assert source["sha256"] in report, "the report names the exact file it was built from"
    assert "Generated by" in report and "partner" in report
    assert "investigateed" not in report.lower()
    assert "audit opinion" in report  # ... in the sentence saying it does not issue one
    assert "invoice seen and agreed" in report


def test_the_csv_carries_a_readable_decision_and_a_stable_code(
    tmp_path: Path, csv_bytes: bytes
) -> None:
    client = _client(tmp_path / "review.db", "partner@firm.in")
    queue = _upload(client, csv_bytes)
    engagement = queue["engagement"]["id"]
    voucher = queue["findings"][0]["voucher_id"]
    client.post(
        f"/api/engagements/{engagement}/decisions", json={"voucher_id": voucher, "action": "accept"}
    )

    frame = pd.read_csv(io.StringIO(client.get(f"/api/engagements/{engagement}/report.csv").text))
    row = frame[frame.voucher_id == voucher].iloc[0]
    assert row.reviewer_decision == "Exception — follow up"
    assert row.status_code == "accept"
    assert row.decided_at.endswith("UTC")


