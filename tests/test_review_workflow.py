def test_the_dashboard_shows_progress_without_reanalysing(tmp_path: Path, csv_bytes: bytes) -> None:
    store = tmp_path / "review.db"
    client = _client(store, "partner@firm.in")
    queue = _upload(client, csv_bytes)
    engagement = queue["engagement"]["id"]
    for finding in queue["findings"][:2]:
        client.post(
            f"/api/engagements/{engagement}/decisions",
            json={"voucher_id": finding["voucher_id"], "action": "investigate"},
        )

    fresh = _client(store, "partner@firm.in")  # a new process: nothing in memory
    (row,) = fresh.get("/api/engagements").json()

    assert row["flagged"] == queue["flagged"]
    assert row["high"] == queue["bands"]["high"]
    assert row["reviewed"] == 2
    assert row["latest_file"] == "books.csv"
    app = cast(FastAPI, fresh.app)
    assert not app.state.workspace.analyses, "listing must not analyse anything"


def test_an_engagement_can_be_renamed_and_the_name_carries_into_the_report(
    tmp_path: Path, csv_bytes: bytes
) -> None:
    client = _client(tmp_path / "review.db", "partner@firm.in")
    engagement = _upload(client, csv_bytes)["engagement"]["id"]

    renamed = client.patch(f"/api/engagements/{engagement}", json={"name": "Sharma Traders — FY25"})
    assert renamed.status_code == 200
    assert client.get("/api/engagements").json()[0]["engagement"]["name"] == "Sharma Traders — FY25"
    assert "Sharma Traders — FY25" in client.get(f"/api/engagements/{engagement}/report.html").text

    assert (
        client.patch(f"/api/engagements/{engagement}", json={"name": "x" * 121}).status_code == 422
    )
    restored = client.patch(f"/api/engagements/{engagement}", json={"name": "  "}).json()
    assert restored["name"] != "  " and restored["name"].strip()


