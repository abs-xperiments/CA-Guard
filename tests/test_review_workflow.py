def test_demo_visitors_never_reach_each_others_engagements(
    tmp_path: Path, csv_bytes: bytes, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("CAGUARD_DEMO", "1")
    store = tmp_path / "review.db"
    alice = _client(store, "alice@example.com")
    queue = _upload(alice, csv_bytes)
    engagement = queue["engagement"]["id"]
    voucher = queue["findings"][0]["voucher_id"]
    (source,) = alice.get(f"/api/engagements/{engagement}/sources").json()

    bob = _client(store, "bob@example.com")
    assert bob.get("/api/engagements").json() == []
    base = f"/api/engagements/{engagement}"
    attempts = [
        ("get", f"{base}/queue", None),
        ("get", f"{base}/findings/{voucher}", None),
        ("get", f"{base}/findings/{voucher}/explanation", None),
        ("post", f"{base}/decisions", {"voucher_id": voucher, "action": "accept"}),
        ("get", f"{base}/trail", None),
        ("get", f"{base}/report.csv", None),
        ("get", f"{base}/report.html", None),
        ("patch", base, {"name": "mine now"}),
        ("get", f"{base}/sources", None),
        ("get", f"{base}/sources/{source['id']}/original", None),
        ("get", f"{base}/sources/{source['id']}/preview", None),
        ("delete", f"{base}/sources/{source['id']}", None),
    ]
    for method, url, body in attempts:
        response = getattr(bob, method)(url, **({"json": body} if body else {}))
        assert response.status_code == 404, (method, url, response.status_code)

    # The same sample ledger uploaded by Bob is his own engagement, not Alice's.
    own = _upload(bob, csv_bytes)["engagement"]["id"]
    assert own != engagement
    assert alice.get(f"{base}/trail").json() == []
    assert len(alice.get("/api/engagements").json()) == 1


