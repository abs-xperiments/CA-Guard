def test_a_version_2_database_upgrades_to_3_and_keeps_everything(
    tmp_path: Path, csv_bytes: bytes
) -> None:
    store = tmp_path / "review.db"
    client = _client(store, "partner@firm.in")
    queue = _upload(client, csv_bytes)
    engagement = queue["engagement"]["id"]
    voucher = queue["findings"][0]["voucher_id"]
    client.post(
        f"/api/engagements/{engagement}/decisions", json={"voucher_id": voucher, "action": "accept"}
    )

    # Rewind the file to version 2, as a previous build would have left it.
    with sqlite3.connect(store) as connection:
        connection.execute("DROP TABLE engagement_stats")
        connection.execute("ALTER TABLE engagements DROP COLUMN display_name")
        connection.execute("ALTER TABLE engagements DROP COLUMN owner_id")
        connection.execute("UPDATE schema_version SET version = 2")

    upgraded = ReviewStore(store)
    with sqlite3.connect(store) as connection:
        assert connection.execute("SELECT version FROM schema_version").fetchone() == (
            SCHEMA_VERSION,
        )
    assert len(upgraded.trail(engagement)) == 1
    assert upgraded.sources(engagement)
    (summary,) = upgraded.summaries()
    assert summary.flagged is None, "unknown until analysed again — not guessed"
    assert summary.reviewed == 1


